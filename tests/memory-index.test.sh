#!/usr/bin/env bash
# Tests for memory-index.sh — synthetic store in a temp dir, so no real index is
# read or written.
#
# The property that matters most is that reordering is a PURE PERMUTATION. An
# index line is the only way the model learns a memory exists, so losing one in
# a sort is a silent, permanent loss.
set -u
SCRIPT_UT="bin/memory-index.sh"
PASS=0; FAIL=0

TMP=$(mktemp -d "${TMPDIR:-/tmp}/cch.XXXXXX")
trap 'rm -rf "$TMP"' EXIT
export CLAUDE_MEMORY_PROJECTS_DIR="$TMP/projects"
STORE="$CLAUDE_MEMORY_PROJECTS_DIR/teststore/memory"
mkdir -p "$STORE"

pass() { echo "  OK: $1"; PASS=$((PASS+1)); }
fail() { echo "  FAIL: $1  $2"; FAIL=$((FAIL+1)); }
check_contains() { case "$3" in *"$2"*) pass "$1" ;; *) fail "$1" "expected: $2" ;; esac; }
check_absent()   { case "$3" in *"$2"*) fail "$1" "unexpected: $2" ;; *) pass "$1" ;; esac; }
check_eq()       { if [ "$3" = "$2" ]; then pass "$1"; else fail "$1" "expect=$2 got=$3"; fi; }

run()    { bash "$SCRIPT_UT" --store teststore "$@" 2>&1; }
run_rc() { bash "$SCRIPT_UT" --store teststore "$@" >/dev/null 2>&1; echo $?; }

mem() {  # mem <stem> <type> [modified]
  local stem="$1" type="$2" mod="${3:-2026-01-01}"
  { echo "---"; echo "name: $stem"; echo "description: d"
    echo "metadata:"; echo "  type: $type"; echo "  modified: $mod"
    echo "---"; echo "body"; } > "$STORE/$stem.md"
}
entry() { echo "- [T]($1.md) — hook"; }
# A date N days back, portable across BSD (macOS) and GNU (CI). Age-floor tests
# must be relative to today or they rot into passing for the wrong reason.
dago() { date -v-"$1"d +%Y-%m-%d 2>/dev/null || date -d "$1 days ago" +%Y-%m-%d; }
# Order of the entries as they appear, by stem.
# The archive pointer is generated by the tool, not one of the store's
# memories, so it is never part of the ordering under test.
order() { grep '^- \[' "$STORE/MEMORY.md" | grep -v '](MEMORY_ARCHIVE\.md)' | sed 's/.*](//; s/\.md).*//' | tr '\n' ' '; }
reset() { rm -f "$STORE"/*.md; }
# An ACTIVE block already carrying the pointer. Tests that assert exactly which
# entries are peeled seed this so the budget is not perturbed by the tool
# adding a pointer (and its marker and blank line) part-way through the drain.
active_with_pointer() {
  echo "<!-- ACTIVE WORK — kept at top so index truncation cannot drop it -->"
  echo "- [ARCHIVE: older memories](MEMORY_ARCHIVE.md) — index lines only."
  echo ""
}

echo "=== entries are grouped feedback, reference, project ==="
reset
mem p1 project; mem r1 reference; mem f1 feedback; mem r2 reference
{ entry p1; entry r1; entry f1; entry r2; } > "$STORE/MEMORY.md"
check_eq "reports out of order" "1" "$(run_rc)"
check_contains "and says so"    "OUT OF ORDER" "$(run)"
run --write >/dev/null
check_eq "grouped by type, append order kept inside each" "f1 r1 r2 p1 " "$(order)"

echo ""
echo "=== feedback is never in the tail, because it does nothing unless loaded ==="
reset
mem f1 feedback; mem f2 feedback; mem r1 reference; mem p1 project
{ entry r1; entry p1; entry f1; entry f2; } > "$STORE/MEMORY.md"
run --write >/dev/null
FIRST=$(grep '^- \[' "$STORE/MEMORY.md" | head -2 | sed 's/.*](//; s/\.md).*//' | tr '\n' ' ')
check_eq "both feedback entries come first" "f1 f2 " "$FIRST"

echo ""
echo "=== project is newest-first, so the tail is the oldest ==="
reset
mem old project 2024-01-01; mem mid project 2025-06-01; mem new project 2026-08-01
{ entry old; entry mid; entry new; } > "$STORE/MEMORY.md"
run --write >/dev/null
check_eq "newest to oldest" "new mid old " "$(order)"

echo ""
echo "=== reference is newest-first too, so the tail is the oldest fact ==="
# The regression this prevents: reference kept append order until 2026-08-31,
# which parked the freshest fact at the truncation edge. On a live store at 197
# of 200 lines, the last two reference entries were both written that same day.
reset
mem rold reference 2026-06-03; mem rmid reference 2026-07-15; mem rnew reference 2026-08-31
{ entry rold; entry rmid; entry rnew; } > "$STORE/MEMORY.md"
run --write >/dev/null
check_eq "newest to oldest" "rnew rmid rold " "$(order)"
LAST=$(grep '^- \[' "$STORE/MEMORY.md" | tail -1 | sed 's/.*](//; s/\.md).*//')
check_eq "the OLDEST fact is the line truncation takes first" "rold" "$LAST"

echo ""
echo "=== same-day reference entries keep their original order ==="
# Real stores land most memories on a handful of busy days, so ties are the
# common case rather than the corner case. `sort -r` alone is not stable and
# would reshuffle same-day entries on every run, so the index would never
# settle and every session would see a different tail.
reset
mem a reference 2026-08-31; mem b reference 2026-08-31; mem c reference 2026-08-31
{ entry a; entry b; entry c; } > "$STORE/MEMORY.md"
run --write >/dev/null
check_eq "ties keep input order" "a b c " "$(order)"
run --write >/dev/null
check_eq "and stay put on a second run" "a b c " "$(order)"

echo ""
echo "=== the ACTIVE block is passed through untouched, at the top ==="
reset
mem a1 project; mem a2 reference; mem f1 feedback
{ echo "<!-- ACTIVE WORK — kept at top so index truncation cannot drop it -->"
  entry a1; entry a2; echo ""; entry f1; } > "$STORE/MEMORY.md"
run --write >/dev/null
check_eq "active entries stay put, in their own order" "a1 a2 f1 " "$(order)"
check_contains "marker kept" "ACTIVE WORK" "$(head -1 "$STORE/MEMORY.md")"

echo ""
echo "=== reordering is a pure permutation ==="
reset
i=0; : > "$STORE/MEMORY.md"
while [ "$i" -lt 30 ]; do
  t=reference; [ $((i % 3)) -eq 0 ] && t=project; [ $((i % 5)) -eq 0 ] && t=feedback
  mem "m$i" "$t" "2026-01-$(printf '%02d' $((i % 28 + 1)))"
  entry "m$i" >> "$STORE/MEMORY.md"
  i=$((i+1))
done
BEFORE=$(grep '^- \[' "$STORE/MEMORY.md" | sort | shasum | awk '{print $1}')
run --write >/dev/null
AFTER=$(grep '^- \[' "$STORE/MEMORY.md" | sort | shasum | awk '{print $1}')
check_eq "same set of entry lines, byte for byte" "$BEFORE" "$AFTER"
check_eq "none lost" "30" "$(grep -c '^- \[' "$STORE/MEMORY.md")"

echo ""
echo "=== an older memory with a top-level type: is still sorted by it ==="
# These exist: `type:` at the top level rather than under `metadata:`. A stricter
# pattern filed 13 of them under REFERENCE while memory-lint, reading the same
# field permissively, called every one misfiled.
reset
mem r1 reference
printf -- '---\nname: oldstyle\ndescription: d\ntype: feedback\n---\nbody\n' > "$STORE/oldstyle.md"
{ entry r1; entry oldstyle; } > "$STORE/MEMORY.md"
run --write >/dev/null
check_eq "the top-level type wins its section" "oldstyle r1 " "$(order)"

echo ""
echo "=== an entry whose memory is missing or untyped is kept, out of the tail ==="
# It sits at the TOP of the reference section, not the bottom. Once reference
# became newest-first, "above project" stopped being enough on its own: in a
# store whose project block is empty the bottom of reference is the end of the
# index, so an orphan parked there would be the first line truncation takes.
reset
mem r1 reference; mem p1 project
{ entry r1; entry p1; entry ghost; } > "$STORE/MEMORY.md"
run --write >/dev/null
check_contains "the orphan entry survives" "ghost" "$(order)"
check_eq "and is not demoted below project" "ghost r1 p1 " "$(order)"

echo ""
echo "=== overflow is archived rather than silently truncated ==="
# At ~14 new memories a day no fixed headroom survives 24 hours, so a live index
# sits permanently at its cap. Ordering decides WHICH line goes over the edge;
# this decides whether anything records that it went.
reset
mem r1 reference 2026-08-31; mem r2 reference 2026-08-30; mem r3 reference 2026-08-29
mem r4 reference 2026-06-02; mem r5 reference 2026-06-01
{ active_with_pointer; entry r1; entry r2; entry r3; entry r4; entry r5; } > "$STORE/MEMORY.md"
# active block 3 + ref marker 1 + 5 entries + trailing blank 1 = 10 lines, so a
# cap of 8 forces the two oldest out.
MEMORY_INDEX_MAX_LINES=8; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
run --archive-overflow >/dev/null
check_eq "the index keeps the newest" "r1 r2 r3 " "$(order)"
ARCH=$(grep '^- \[' "$STORE/MEMORY_ARCHIVE.md" | sed 's/.*](//; s/\.md).*//' | tr '\n' ' ')
check_eq "the two oldest moved to the archive" "r5 r4 " "$ARCH"
check_eq "and the index is inside the cap" "yes" "$([ "$(wc -l < "$STORE/MEMORY.md")" -le 8 ] && echo yes || echo no)"

echo ""
echo "=== the drain goes BELOW the cap, so the index survives between runs ==="
# Draining to exactly the cap would put the index back over it after a single
# new memory, and everything past the cap until the next run is dropped with
# nothing recording it.
reset
i=1
active_with_pointer > "$STORE/MEMORY.md"
while [ $i -le 9 ]; do
  mem "d$i" reference "2026-08-0$i"
  entry "d$i" >> "$STORE/MEMORY.md"
  i=$((i+1))
done
# 3 + 1 + 9 + 1 = 14 lines. Cap 12 trips it; margin 3 drains to 9, not to 12.
MEMORY_INDEX_MAX_LINES=12; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=3; export MEMORY_INDEX_ARCHIVE_MARGIN
run --archive-overflow >/dev/null
check_eq "drained under cap-minus-margin" "yes" "$([ "$(wc -l < "$STORE/MEMORY.md")" -le 9 ] && echo yes || echo no)"
check_contains "the newest fact is still indexed" "d9" "$(order)"

echo ""
echo "=== archiving leaves a pointer, so the archive is not invisible ==="
# An index line is the only way the model learns a memory exists, so an archive
# with nothing pointing at it is the same as a deletion.
reset
i=1; : > "$STORE/MEMORY.md"
while [ $i -le 6 ]; do
  mem "q$i" reference "2026-08-0$i"
  entry "q$i" >> "$STORE/MEMORY.md"
  i=$((i+1))
done
MEMORY_INDEX_MAX_LINES=5; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
run --archive-overflow >/dev/null
check_contains "the index points at the archive" "MEMORY_ARCHIVE.md" "$(cat "$STORE/MEMORY.md")"
check_eq "exactly one pointer" "1" "$(grep -c 'MEMORY_ARCHIVE\.md' "$STORE/MEMORY.md")"
run --archive-overflow >/dev/null
check_eq "and a second run does not duplicate it" "1" "$(grep -c 'MEMORY_ARCHIVE\.md' "$STORE/MEMORY.md")"

echo ""
echo "=== a healthy index is never peeled ==="
reset
mem h1 reference 2026-08-31; mem h2 reference 2026-08-30
{ entry h1; entry h2; } > "$STORE/MEMORY.md"
MEMORY_INDEX_MAX_LINES=200; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=15; export MEMORY_INDEX_ARCHIVE_MARGIN
run --archive-overflow >/dev/null
check_eq "both entries stay put" "h1 h2 " "$(order)"
check_eq "no archive created" "no" "$([ -f "$STORE/MEMORY_ARCHIVE.md" ] && echo yes || echo no)"

echo ""
echo "=== peeling preserves every entry across the PAIR of files ==="
# The invariant that matters: an entry may move, but it may never vanish.
reset
i=1; : > "$STORE/MEMORY.md"
while [ $i -le 12 ]; do
  mem "m$i" reference "2026-08-$(printf '%02d' $i)"
  entry "m$i" >> "$STORE/MEMORY.md"
  i=$((i+1))
done
MEMORY_INDEX_MAX_LINES=6; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
run --archive-overflow >/dev/null
BOTH=$(cat "$STORE/MEMORY.md" "$STORE/MEMORY_ARCHIVE.md" | grep '^- \[' | grep -v '](MEMORY_ARCHIVE\.md)' | sed 's/.*](//; s/\.md).*//' | sort | tr '\n' ' ')
check_eq "all twelve are still indexed somewhere" "m1 m10 m11 m12 m2 m3 m4 m5 m6 m7 m8 m9 " "$BOTH"

echo ""
echo "=== project is peeled before reference, even when it is newer ==="
# Type beats age AMONG AGE-ELIGIBLE ENTRIES: project is the only lifecycle-bound
# type, so it is the archive-eligible end regardless of which entry happens to be
# fresher. The age floor is switched off here on purpose - it outranks tier
# precedence and has its own block below; this test is about the precedence.
reset
mem r1 reference 2026-01-01; mem p1 project "$(dago 30)"
{ active_with_pointer; entry r1; entry p1; } > "$STORE/MEMORY.md"
# 3 + (ref marker + r1 + blank) + (proj marker + p1) = 8. Cap 7 peels exactly one.
MEMORY_INDEX_MAX_LINES=7; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS=0; export MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS
run --archive-overflow >/dev/null
check_eq "the newer project entry goes first" "r1 " "$(order)"

echo ""
echo "=== the age floor outranks tier cheapness ==="
# The regression this exists for: on two consecutive days the drain took a
# `project` memory written that same morning - the freshest, most actionable
# entry in the store - because project is the cheapest TIER and that memory was
# the only thing in it. Tier is an INDIRECT proxy for cost-of-loss and a
# nearly-empty tier defeats it; recency is a direct signal, so it wins.
reset
mem r1 reference 2026-01-01; mem p1 project "$(dago 0)"
{ active_with_pointer; entry r1; entry p1; } > "$STORE/MEMORY.md"
MEMORY_INDEX_MAX_LINES=7; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS=2; export MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS
run --archive-overflow >/dev/null
check_eq "today's project entry is spared" "p1 " "$(order)"
ARCH=$(grep '^- \[' "$STORE/MEMORY_ARCHIVE.md" | sed 's/.*](//; s/\.md).*//' | tr '\n' ' ')
check_eq "the old reference went instead" "r1 " "$ARCH"

echo ""
echo "=== an entry exactly ON the floor is still eligible ==="
# The boundary is <=, so a memory dated exactly N days back is peelable. Without
# this the floor would quietly widen by a day.
reset
mem r1 reference "$(dago 2)"; mem r2 reference "$(dago 0)"
{ active_with_pointer; entry r2; entry r1; } > "$STORE/MEMORY.md"
MEMORY_INDEX_MAX_LINES=6; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS=2; export MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS
run --archive-overflow >/dev/null
check_eq "the entry on the boundary is peeled" "r2 " "$(order)"

echo ""
echo "=== a floor that blocks everything stops short and SAYS so ==="
# A silently-short drain is indistinguishable from a completed one, which is the
# failure mode this whole tool exists to remove. Better an honest overage.
reset
mem r1 reference "$(dago 0)"; mem r2 reference "$(dago 0)"
{ active_with_pointer; entry r1; entry r2; } > "$STORE/MEMORY.md"
MEMORY_INDEX_MAX_LINES=5; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS=2; export MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS
OUT=$(run --archive-overflow)
check_eq "nothing was peeled"       "r1 r2 " "$(order)"
case "$OUT" in *"stopped short"*)  pass "it reports the short drain" ;;
               *) fail "it reports the short drain" "no mention: $OUT" ;; esac
case "$OUT" in *"age floor"*)      pass "and names the age floor"   ;;
               *) fail "and names the age floor" "no mention: $OUT" ;; esac
check_eq "no archive is written when nothing is eligible" "no" \
  "$([ -f "$STORE/MEMORY_ARCHIVE.md" ] && echo yes || echo no)"

# Leave the floor OFF for the remaining tests, which predate it and pin drain
# mechanics rather than recency.
MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS=0; export MEMORY_INDEX_ARCHIVE_MIN_AGE_DAYS

echo ""
echo "=== feedback is never peeled, however tight the budget ==="
# Rules do nothing unless loaded, so they are not overflow. The loop must also
# terminate once nothing peelable is left rather than spin.
reset
mem f1 feedback; mem f2 feedback; mem r1 reference 2026-01-01
{ entry f1; entry f2; entry r1; } > "$STORE/MEMORY.md"
MEMORY_INDEX_MAX_LINES=1; export MEMORY_INDEX_MAX_LINES
MEMORY_INDEX_ARCHIVE_MARGIN=0; export MEMORY_INDEX_ARCHIVE_MARGIN
run --archive-overflow >/dev/null
check_eq "both rules survive an impossible budget" "f1 f2 " "$(order)"

echo ""
echo "=== without the flag, an over-budget index is left intact ==="
reset
mem r1 reference 2026-08-31; mem r2 reference 2026-01-01
{ entry r1; entry r2; } > "$STORE/MEMORY.md"
MEMORY_INDEX_MAX_LINES=1; export MEMORY_INDEX_MAX_LINES
run --write >/dev/null
check_eq "both entries stay in the index" "r1 r2 " "$(order)"
check_eq "and no archive is created" "no" "$([ -f "$STORE/MEMORY_ARCHIVE.md" ] && echo yes || echo no)"
unset MEMORY_INDEX_MAX_LINES MEMORY_INDEX_ARCHIVE_MARGIN

echo ""
echo "=== a second run changes nothing ==="
BEFORE=$(shasum < "$STORE/MEMORY.md" | awk '{print $1}')
check_eq "reports already ordered" "0" "$(run_rc)"
run --write >/dev/null
AFTER=$(shasum < "$STORE/MEMORY.md" | awk '{print $1}')
check_eq "byte-identical" "$BEFORE" "$AFTER"

echo ""
echo "=== check mode never writes ==="
reset
mem p1 project; mem f1 feedback
{ entry p1; entry f1; } > "$STORE/MEMORY.md"
BEFORE=$(shasum < "$STORE/MEMORY.md" | awk '{print $1}')
run >/dev/null 2>&1
check_eq "unchanged after a check run" "$BEFORE" "$(shasum < "$STORE/MEMORY.md" | awk '{print $1}')"

echo ""
echo "=== an unknown store is an error, not a silent success ==="
check_eq "exit 3" "3" "$(bash "$SCRIPT_UT" --store nosuchstore >/dev/null 2>&1; echo $?)"

echo ""
echo ""
echo "=== a line that is not an entry aborts, rather than being dropped ==="
# The permutation check filters both sides with `^- [`, the same predicate the
# reordering uses, so a line failing that predicate is equally absent from both
# and the check passes while the line disappears. Measured on a live store: an
# append with no trailing newline left a shell command fused to the front of an
# entry, and the memory silently left the index.
mem stray_a feedback
mem stray_b feedback
{ echo "- [T](stray_a.md) — hook"
  echo "grep -c . MEMORY.md; tail -2 MEMORY.md- [T](stray_b.md) — hook"; } > "$STORE/MEMORY.md"
BEFORE=$(cat "$STORE/MEMORY.md")
OUT=$(run --write)
check_contains "a stray line is named"        "neither an entry nor a tier marker" "$OUT"
check_contains "the stray's text is shown"    "stray_b.md"                          "$OUT"
check_contains "says why it would be lost"    "discard them silently"               "$OUT"
check_contains "names the likely cause"       "no trailing newline"                 "$OUT"
check_eq       "aborts with 3"                "3" "$(run_rc --write)"
check_eq       "and writes nothing"           "$BEFORE" "$(cat "$STORE/MEMORY.md")"

# A tier marker is a comment, not a stray, and must not trip the guard.
{ echo "<!-- FEEDBACK — how to work -->"
  echo "- [T](stray_a.md) — hook"
  echo "- [T](stray_b.md) — hook"; } > "$STORE/MEMORY.md"
OUT=$(run --write)
check_absent "a tier marker is not a stray" "neither an entry nor a tier marker" "$OUT"

echo ""
echo "--- Results: $PASS passed, $FAIL failed ---"
[ "$FAIL" -eq 0 ]
